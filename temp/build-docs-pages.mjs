// B) catch-all doc route — load
mkdirSync(`${base}/[...doc]`, { recursive: true });
writeFileSync(
	`${base}/[...doc]/+page.ts`,
	[
		"import { fractalAgentic } from '$lib/docs/fractalagentic';",
		"import type { PageLoad } from './$types';",
		'',
		'// Resolve the compiled article in load (kit-consumer pattern) so the prose lands in the',
		'// SSR HTML. Only serializable document fields ride through data; the component is passed',
		'// as Article.',
		'export const load: PageLoad = async ({ params }) => {',
		"\tconst pathname = '/docs/fractalagentic/' + params.doc;",
		'\tconst document =',
		'\t\tfractalAgentic.get(pathname) ??',
		'\t\tfractalAgentic.documents.find((entry) => entry.slug === params.doc);',
		'\treturn {',
		'\t\tpathname,',
		'\t\tArticle: document ? await document.loader() : undefined,',
		'\t\tdocument: document',
		'\t\t\t? {',
		'\t\t\t\t\ttitle: document.title,',
		'\t\t\t\t\tdescription: document.description,',
		'\t\t\t\t\tmetadata: document.metadata',
		'\t\t\t\t}',
		'\t\t\t: undefined',
		'\t};',
		'};',
		''
	].join('\n')
);

// C) catch-all doc route — page
writeFileSync(
	`${base}/[...doc]/+page.svelte`,
	[
		'<script lang="ts">',
		"\timport { page } from '$app/state';",
		'',
		'\tlet { data } = $props();',
		'',
		'\tconst metadata = $derived(',
		'\t\t(data.document?.metadata ?? {}) as { tags?: string[]; type?: string }',
		'\t);',
		'\tconst tags = $derived(metadata.tags ?? []);',
		'\tconst crumbs = $derived.by(() => {',
		"\t\tconst segments = page.url.pathname.split('/').filter(Boolean);",
		'\t\treturn segments.map((segment, index) => ({',
		"\t\t\tlabel: segment.replace(/^\\d{2}-/, '').replaceAll('-', ' '),",
		"\t\t\thref: '/' + segments.slice(0, index + 1).join('/'),",
		'\t\t\tisCurrent: index === segments.length - 1',
		'\t\t}));',
		'\t});',
		'</script>',
		'',
		'<svelte:head>',
		"\t<title>{data.document?.title ?? 'Not found'} · Fractalsvelte</title>",
		'</svelte:head>',
		'',
		'<main class="page-shell box gap-3xl">',
		'\t{#if data.document && data.Article}',
		'\t\t<article class="content-shell box gap-md wfull">',
		'\t\t\t<header class="box gap-xs wfull">',
		'\t\t\t\t<nav class="row ycenter wrap gap-3xs">',
		'\t\t\t\t\t{#each crumbs as crumb (crumb.href)}',
		'\t\t\t\t\t\t{#if crumb.isCurrent}',
		'\t\t\t\t\t\t\t<span class="text-xs text-muted tt-c">{crumb.label}</span>',
		'\t\t\t\t\t\t{:else}',
		'\t\t\t\t\t\t\t<a class="text-xs text-muted" href={crumb.href}>{crumb.label}</a>',
		'\t\t\t\t\t\t{/if}',
		'\t\t\t\t\t{/each}',
		'\t\t\t\t</nav>',
		'\t\t\t\t<h1 class="text-3xl weight-600">{data.document.title}</h1>',
		'\t\t\t\t{#if data.document.description}',
		'\t\t\t\t\t<p class="text-md text-secondary">{data.document.description}</p>',
		'\t\t\t\t{/if}',
		'\t\t\t\t{#if metadata.type || tags.length > 0}',
		'\t\t\t\t\t<div class="row ycenter wrap gap-3xs">',
		'\t\t\t\t\t\t{#if metadata.type}<span class="badge text-xs">{metadata.type}</span>{/if}',
		'\t\t\t\t\t\t{#each tags as tag (tag)}',
		'\t\t\t\t\t\t\t<span class="badge text-xs">{tag}</span>',
		'\t\t\t\t\t\t{/each}',
		'\t\t\t\t\t</div>',
		'\t\t\t\t{/if}',
		'\t\t\t</header>',
		'\t\t\t<div class="prose wfull">',
		'\t\t\t\t<data.Article />',
		'\t\t\t</div>',
		'\t\t</article>',
		'\t{:else}',
		'\t\t<section class="card box gap-sm pad-lg surface border radius-md">',
		'\t\t\t<span class="eyebrow text-theme">404</span>',
		'\t\t\t<h1 class="text-3xl weight-600">Documentation page not found</h1>',
		'\t\t\t<p class="text-md text-secondary">',
		'\t\t\t\tNo document lives at <code class="mono text-sm">{data.pathname}</code>.',
		'\t\t\t\t<a href="/docs/fractalagentic">Back to the handbook index</a>.',
		'\t\t\t</p>',
		'\t\t</section>',
		'\t{/if}',
		'</main>',
		''
	].join('\n')
);

